// Write the GitHub issue forms in .github/ISSUE_TEMPLATE/ from scripts/forms-spec.mjs.
// Run after a build so the dropdowns match the data:   npm run forms
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { formSpecs } from './forms-spec.mjs';

const ROOT = new URL('../', import.meta.url);
const cfg = JSON.parse(await readFile(new URL('site.config.json', ROOT), 'utf8'));
const site = JSON.parse(await readFile(new URL('dist/data/site.json', ROOT), 'utf8'));
const cities = site.places.map((p) => `${p.name} (${p.state})`).sort((a, b) => a.localeCompare(b));
const specs = formSpecs(site.vocab, cities);
const dir = new URL('.github/ISSUE_TEMPLATE/', ROOT);
await mkdir(dir, { recursive: true });

const q = (s) => JSON.stringify(String(s)); // JSON strings are valid YAML scalars
function fieldYaml(f) {
  const lines = [`  - type: ${f.type}`, `    id: ${f.id}`, '    attributes:', `      label: ${q(f.label)}`];
  if (f.description) lines.push(`      description: ${q(f.description)}`);
  if (f.placeholder) lines.push(`      placeholder: ${q(f.placeholder)}`);
  if (f.type === 'dropdown') {
    if (f.multiple) lines.push('      multiple: true');
    lines.push('      options:', ...f.options.map((o) => `        - ${q(o)}`));
  }
  if (f.type === 'checkboxes') lines.push('      options:', ...f.options.flatMap((o) => [`        - label: ${q(o.label)}`, ...(o.required ? ['          required: true'] : [])]));
  if (f.required && f.type !== 'checkboxes') lines.push('    validations:', '      required: true');
  return lines.join('\n');
}
for (const [slug, s] of Object.entries(specs)) {
  const yaml = [
    `# Generated by scripts/forms.mjs from scripts/forms-spec.mjs. Edit those, then run: npm run forms`,
    `name: ${q(s.name)}`, `description: ${q(s.description)}`, `title: ${q(s.title)}`, `labels: [${s.labels.map(q).join(', ')}]`,
    'body:', '  - type: markdown', '    attributes:', `      value: ${q(`${s.intro} See the [contribution guide](${cfg.baseUrl}about/#contribute) for what makes a good suggestion.`)}`,
    ...s.fields.map(fieldYaml), '',
  ].join('\n');
  await writeFile(new URL(`${slug}.yml`, dir), yaml);
}
await writeFile(new URL('config.yml', dir), [
  '# Generated by scripts/forms.mjs',
  'blank_issues_enabled: false',
  'contact_links:',
  `  - name: ${q('How to contribute')}`,
  `    url: ${q(`${cfg.baseUrl}about/#contribute`)}`,
  `    about: ${q('What we collect, what counts as a source, and how suggestions are reviewed.')}`, '',
].join('\n'));
console.log(`✓ Wrote ${Object.keys(specs).length} issue forms to .github/ISSUE_TEMPLATE/ (${cities.length} cities in the dropdowns)`);
